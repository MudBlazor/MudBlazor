namespace MudBlazor;

/// <summary>
/// Specifies whether a series is drawn as a plain line or as a line with the area beneath it filled.
/// </summary>
public enum LineDisplayType
{
    /// <summary>
    /// Display as a plain line.
    /// </summary>
    Line,
    /// <summary>
    /// Display as a line with the area below it filled.
    /// </summary>
    Area,
}
